// Верхня межа для цілих полів (тривалість, рік, ціна). MongoDB зберігає Number як double,
// тож без межі завеликі числа втрачали б точність. З такою межею навіть підсумкова ціна
// найбільшого бронювання (10 000 місць) лишається точним цілим
export const MAX_INTEGER = 2_147_483_647;

// Розмір залу: обмеження тримає масив місць сеансу (rows × seatsPerRow) у розумних межах,
// тож документ сеансу не росте безмежно
export const MAX_HALL_ROWS = 100;
export const MAX_SEATS_PER_ROW = 100;
